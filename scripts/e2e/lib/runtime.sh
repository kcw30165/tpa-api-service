#!/usr/bin/env bash
set -euo pipefail
: "${E2E_ENVIRONMENT:=local}"
: "${E2E_BOOTSTRAP_MODE:=anonymous}"
: "${E2E_CONNECT_TIMEOUT_SECONDS:=5}"
: "${E2E_REQUEST_TIMEOUT_SECONDS:=20}"
: "${E2E_TLS_VERIFY:=true}"
: "${ACCEPT_LANGUAGE:=en}"
: "${REQUEST_ID_PREFIX:=bff-e2e}"
: "${E2E_ALLOW_EXTERNAL_EFFECTS:=false}"
: "${E2E_ALLOW_MUTATIONS:=false}"
export E2E_ENVIRONMENT E2E_BOOTSTRAP_MODE E2E_CONNECT_TIMEOUT_SECONDS
export E2E_REQUEST_TIMEOUT_SECONDS E2E_TLS_VERIFY ACCEPT_LANGUAGE REQUEST_ID_PREFIX
export E2E_ALLOW_EXTERNAL_EFFECTS E2E_ALLOW_MUTATIONS
